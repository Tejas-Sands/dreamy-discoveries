/**
 * Turns library/characters/*.json and library/backgrounds/*.json into
 * src/generated/registry.ts so Remotion bundles exactly the recipes that exist.
 * Runs automatically before studio/render; run it by hand after adding a recipe.
 */
import fs from "node:fs";
import path from "node:path";
import { ROOT } from "./lib/common.mjs";
import { scanVox } from "./lib/vox.mjs";

const LIB = path.join(ROOT, "library");
const OUT = path.join(ROOT, "src", "generated", "registry.ts");
const ident = (name) => name.replace(/[^a-zA-Z0-9_]/g, "_");

function collect(kind) {
  const dir = path.join(LIB, kind);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .map((f) => ({ name: path.basename(f, ".json"), file: `../../library/${kind}/${f}` }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

export function buildRegistry() {
  const chars = collect("characters");
  const bgs = collect("backgrounds");
  const vox = scanVox();
  const lines = [
    "/* GENERATED by scripts/build-registry.mjs — do not edit. Add recipes under library/ instead. */",
    'import type { CharacterRecipe } from "../components/characters/recipe";',
    'import type { BackgroundRecipe } from "../components/backgrounds/recipe";',
    ...chars.map((c) => `import c_${ident(c.name)} from "${c.file}";`),
    ...bgs.map((b) => `import b_${ident(b.name)} from "${b.file}";`),
    "",
    "export const CHARACTER_RECIPES: Record<string, CharacterRecipe> = {",
    ...chars.map((c) => `  "${c.name}": c_${ident(c.name)} as unknown as CharacterRecipe,`),
    "};",
    "",
    "export const BACKGROUND_RECIPES: Record<string, BackgroundRecipe> = {",
    ...bgs.map((b) => `  "${b.name}": b_${ident(b.name)} as unknown as BackgroundRecipe,`),
    "};",
    "",
    `export const CHARACTER_NAMES = ${JSON.stringify(chars.map((c) => c.name))};`,
    `export const BACKGROUND_NAMES = ${JSON.stringify(bgs.map((b) => b.name))};`,
    "",
    "/** recorded vocalizations on disk (public/vox + public/vox-local), by kind */",
    `export const VOX: Record<string, Array<{ file: string; durationSec: number }>> = ${JSON.stringify(vox)};`,
    "",
  ];
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  const next = lines.join("\n");
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, "utf8") !== next) fs.writeFileSync(OUT, next);
  return { characters: chars.length, backgrounds: bgs.length, vox: Object.fromEntries(Object.entries(vox).map(([k, v]) => [k, v.length])) };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === new URL(import.meta.url).pathname;
if (isMain) {
  const r = buildRegistry();
  const voxCount = Object.values(r.vox).reduce((a, b) => a + b, 0);
  console.log(`[registry] ${r.characters} characters, ${r.backgrounds} backgrounds, ${voxCount} vocalizations → src/generated/registry.ts`);
}
